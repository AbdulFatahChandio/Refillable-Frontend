export function findCountryByCode(code?: string | null) {
  if (!code) return undefined;
  return COUNTRIES_CURRENCIES.find(
    (c) => c.countryCode.toUpperCase() === code.toUpperCase(),
  );
}

export function findCountryByCurrency(currency?: string | null) {
  if (!currency) return undefined;
  return COUNTRIES_CURRENCIES.find(
    (c) => c.currency.toUpperCase() === currency.toUpperCase(),
  );
}

/** Unique currencies from all countries, sorted A–Z */
export function getUniqueCurrencies() {
  const seen = new Set<string>();
  const currencies: { currency: string; country: CountryCurrency }[] = [];

  for (const country of COUNTRIES_CURRENCIES) {
    if (seen.has(country.currency)) continue;
    seen.add(country.currency);
    currencies.push({ currency: country.currency, country });
  }

  return currencies.sort((a, b) => a.currency.localeCompare(b.currency));
}
